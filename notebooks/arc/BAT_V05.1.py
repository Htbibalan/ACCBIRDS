    def _tracking_scale_factors(self, frame_shape):
        if not frame_shape or len(frame_shape) < 2:
            return 1.0, 1.0
        fh, fw = int(frame_shape[0]), int(frame_shape[1])
        if self.source_frame_w > 0 and self.source_frame_h > 0:
            return fw / float(self.source_frame_w), fh / float(self.source_frame_h)
        return 1.0, 1.0

    def _tracking_row_index(self, track: dict, frame_idx: int):
        if track is None:
            return None

        n_frames = int(track.get("n_frames", 0) or 0)
        frame_idx = int(frame_idx)

        frame_to_row = track.get("frame_to_row", None)
        if frame_to_row is not None and frame_idx in frame_to_row:
            return int(frame_to_row[frame_idx])

        frames = track.get("frame_numbers", None)
        if frames is not None and len(frames) > 0:
            try:
                pos = int(np.searchsorted(frames, frame_idx))
            except Exception:
                pos = -1
            best = None
            best_diff = None
            for cand in (pos - 1, pos):
                if 0 <= cand < len(frames):
                    diff = abs(int(frames[cand]) - frame_idx)
                    if best is None or diff < best_diff:
                        best = int(cand)
                        best_diff = diff
            if best is not None and best_diff is not None and best_diff <= 1:
                return best

        if 0 <= frame_idx < n_frames:
            return frame_idx
        return None

    def _get_tracking_points_for_frame(self, track: dict, frame_idx: int, frame_shape):
        row_idx = self._tracking_row_index(track, frame_idx)
        if row_idx is None:
            return None

        min_likelihood = self._tracking_likelihood_threshold()
        sx, sy = self._tracking_scale_factors(frame_shape)
        fh, fw = int(frame_shape[0]), int(frame_shape[1])

        points = []
        for bp in track.get("bodyparts", []):
            entry = track.get("points", {}).get(bp, None)
            if entry is None:
                continue
            try:
                x = float(entry["x"][row_idx])
                y = float(entry["y"][row_idx])
                lk = float(entry["likelihood"][row_idx]) if entry.get("likelihood", None) is not None else 1.0
            except Exception:
                continue
            if not np.isfinite(x) or not np.isfinite(y):
                continue
            if np.isfinite(lk) and lk < min_likelihood:
                continue

            px = x * sx
            py = y * sy
            if not np.isfinite(px) or not np.isfinite(py):
                continue
            if px < -2 or py < -2 or px > fw + 2 or py > fh + 2:
                continue
            points.append({"bodypart": bp, "x": float(px), "y": float(py), "likelihood": lk})

        centroid = None
        if points:
            centroid = (
                float(sum(p["x"] for p in points)) / max(1, len(points)),
                float(sum(p["y"] for p in points)) / max(1, len(points)),
            )

        return {"row_idx": int(row_idx), "points": points, "centroid": centroid}

