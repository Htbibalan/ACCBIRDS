    def _widget_blocks_shortcuts(self, widget=None) -> bool:
        w = widget
        if w is None:
            try:
                w = self.root.focus_get()
            except Exception:
                w = None
        if w is None:
            return False
        try:
            cls = str(w.winfo_class() or "")
        except Exception:
            cls = ""
        if cls in {"Entry", "TEntry", "Spinbox", "TSpinbox", "Text", "TCombobox", "Combobox"}:
            return True
        return False

