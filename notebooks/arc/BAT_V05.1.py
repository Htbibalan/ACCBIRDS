    def _hit_test_tracked_animal_at_canvas(self, x: int, y: int):
        if not self.animal_tracks:
            return None
        pt = self._canvas_to_frame(x, y, clamp=False)
        if pt is None:
            return None

        fx, fy = pt
        frame_shape = (max(1, self._frame_h), max(1, self._frame_w))
        hits = []
        for aid, tr in self.animal_tracks.items():
            pts = self._get_tracking_points_for_frame(tr, self.cur_frame_idx, frame_shape)
            if pts is None:
                continue
            for p in pts.get("points", []):
                dist = math.hypot(float(fx) - float(p["x"]), float(fy) - float(p["y"]))
                if dist <= 16.0:
                    hits.append((dist, aid))
            centroid = pts.get("centroid", None)
            if centroid is not None:
                dist = math.hypot(float(fx) - float(centroid[0]), float(fy) - float(centroid[1]))
                if dist <= 20.0:
                    hits.append((dist, aid))

        if not hits:
            return None
        hits.sort(key=lambda z: z[0])
        return int(hits[0][1])

