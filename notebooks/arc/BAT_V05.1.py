    def _read_tracking_hdf(self, path: str):
        try:
            return pd.read_hdf(path)
        except Exception:
            with pd.HDFStore(path, mode="r") as store:
                keys = list(store.keys())
                if not keys:
                    raise ValueError("No tables were found in the HDF5 file.")
                return store[keys[0]]

    def _parse_tracking_csv(self, path: str):
        header_lines = []
        with open(path, "r", encoding="utf-8-sig", errors="ignore") as f:
            for _ in range(4):
                header_lines.append((f.readline() or "").strip())

        first_tokens = [line.split(",")[0].strip().lower() if line else "" for line in header_lines]

        if len(first_tokens) >= 3 and first_tokens[0] == "scorer" and first_tokens[1] == "bodyparts" and first_tokens[2] == "coords":
            df = pd.read_csv(path, header=[0, 1, 2])
            return self._parse_tracking_dataframe(df, path)

        if (
            len(first_tokens) >= 4
            and first_tokens[0] == "scorer"
            and first_tokens[1] == "individuals"
            and first_tokens[2] == "bodyparts"
            and first_tokens[3] == "coords"
        ):
            df = pd.read_csv(path, header=[0, 1, 2, 3])
            return self._parse_tracking_dataframe(df, path)

        df = pd.read_csv(path)
        return self._parse_tracking_dataframe(df, path)

    def _parse_tracking_dataframe(self, df, path: str):
        if isinstance(df, pd.DataFrame) and isinstance(df.columns, pd.MultiIndex):
            return self._parse_multiindex_tracking_dataframe(df, path)
        return self._parse_flat_tracking_dataframe(df, path)

