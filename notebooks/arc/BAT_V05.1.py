    def _find_generated_dlc_output(self, video_path: str, started_at: float = None):
        root_dir = os.path.dirname(video_path) or "."
        stem = os.path.splitext(os.path.basename(video_path))[0]
        candidates = []
        for pattern in (f"{stem}*.h5", f"{stem}*.csv"):
            candidates.extend(glob.glob(os.path.join(root_dir, pattern)))

        ranked = []
        for p in candidates:
            base = os.path.basename(p).lower()
            if base == os.path.basename(video_path).lower():
                continue
            if ("dlc" not in base) and ("shuffle" not in base) and (not p.lower().endswith(".h5")):
                continue
            score = 0
            if "dlc" in base:
                score += 4
            if "shuffle" in base:
                score += 2
            if p.lower().endswith(".h5"):
                score += 1
            try:
                mtime = os.path.getmtime(p)
            except Exception:
                mtime = 0.0
            if started_at is not None and mtime >= (started_at - 5.0):
                score += 6
            ranked.append((score, mtime, p))

        if not ranked:
            return None

        ranked.sort(key=lambda z: (z[0], z[1]), reverse=True)
        return ranked[0][2]

