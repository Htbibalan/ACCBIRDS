    def _parse_multiindex_tracking_dataframe(self, df, path: str):
        coord_names = {"x", "y", "likelihood", "confidence", "conf", "p"}
        nlevels = int(df.columns.nlevels)
        coord_level = nlevels - 1
        bodypart_level = max(0, nlevels - 2)
        individual_level = nlevels - 3 if nlevels >= 4 else None

        tracking_cols = []
        for col in df.columns:
            coord = str(col[coord_level]).strip().lower()
            if coord in coord_names:
                tracking_cols.append(col)

        if not tracking_cols:
            return self._parse_flat_tracking_dataframe(df.reset_index(), path)

        individuals = []
        if individual_level is not None:
            seen = set()
            for col in tracking_cols:
                ind = str(col[individual_level]).strip()
                if not ind:
                    continue
                low = ind.lower()
                if low in {"", "individual", "individuals", "single"}:
                    continue
                if ind not in seen:
                    seen.add(ind)
                    individuals.append(ind)

        selected_individual = self._choose_tracking_individual(individuals, path) if individuals else ""

        filtered_cols = []
        for col in tracking_cols:
            if selected_individual and individual_level is not None:
                if str(col[individual_level]).strip() != selected_individual:
                    continue
            filtered_cols.append(col)

        bodyparts = []
        points = {}
        for col in filtered_cols:
            bp = str(col[bodypart_level]).strip()
            if not bp:
                continue
            if bp not in bodyparts:
                bodyparts.append(bp)

        for bp in bodyparts:
            xcol = None
            ycol = None
            lcol = None
            for col in filtered_cols:
                if str(col[bodypart_level]).strip() != bp:
                    continue
                coord = self._normalize_coord_name(col[coord_level])
                if coord == "x" and xcol is None:
                    xcol = col
                elif coord == "y" and ycol is None:
                    ycol = col
                elif coord == "likelihood" and lcol is None:
                    lcol = col
            if xcol is None or ycol is None:
                continue

            x = pd.to_numeric(df[xcol], errors="coerce").to_numpy(dtype=np.float32)
            y = pd.to_numeric(df[ycol], errors="coerce").to_numpy(dtype=np.float32)
            if lcol is not None:
                likelihood = pd.to_numeric(df[lcol], errors="coerce").to_numpy(dtype=np.float32)
            else:
                likelihood = np.ones(len(df), dtype=np.float32)
            points[bp] = {"x": x, "y": y, "likelihood": likelihood}

        if not points:
            raise ValueError("No usable x/y coordinate columns were found in the tracking file.")

        frame_numbers = self._infer_frame_numbers_from_dataframe(df)
        return {
            "path": path,
            "format_name": "DeepLabCut / multi-index table",
            "selected_individual": selected_individual,
            "bodyparts": [bp for bp in bodyparts if bp in points],
            "points": points,
            "n_frames": int(len(df)),
            "frame_numbers": frame_numbers,
            "frame_to_row": {int(v): int(i) for i, v in enumerate(frame_numbers)},
        }

    def _infer_frame_numbers_from_dataframe(self, df):
        numeric_candidates = []
        if isinstance(df.columns, pd.MultiIndex):
            for col in df.columns:
                leaf = str(col[-1]).strip().lower()
                if leaf in {"x", "y", "likelihood", "confidence", "conf", "p"}:
                    continue
                numeric_candidates.append(col)
        else:
            numeric_candidates.extend(list(df.columns))

        for col in numeric_candidates:
            try:
                ser = pd.to_numeric(df[col], errors="coerce")
            except Exception:
                continue
            valid_ratio = float(ser.notna().mean()) if len(ser) else 0.0
            if valid_ratio < 0.95:
                continue
            vals = ser.to_numpy(dtype=np.float64)
            if len(vals) <= 1:
                continue
            vals_round = np.round(vals).astype(np.int64)
            if np.max(np.abs(vals - vals_round)) > 1e-6:
                continue
            diffs = np.diff(vals_round)
            if np.any(diffs < 0):
                continue
            if len(vals_round) and vals_round[0] == 1 and np.array_equal(vals_round, np.arange(1, len(vals_round) + 1)):
                vals_round = vals_round - 1
            return vals_round.astype(np.int64)

        try:
            idx = pd.to_numeric(pd.Series(df.index), errors="coerce").to_numpy(dtype=np.float64)
            if len(idx) == len(df) and np.isfinite(idx).all():
                idx_round = np.round(idx).astype(np.int64)
                if len(idx_round) and idx_round[0] == 1 and np.array_equal(idx_round, np.arange(1, len(idx_round) + 1)):
                    idx_round = idx_round - 1
                return idx_round.astype(np.int64)
        except Exception:
            pass

        return np.arange(len(df), dtype=np.int64)

    def _parse_flat_tracking_dataframe(self, df, path: str):
        if not isinstance(df, pd.DataFrame):
            raise ValueError("Unsupported tracking table format.")

        cols = [str(c).strip() for c in df.columns]
        frame_col = None
        frame_name_candidates = {"frame", "frames", "frame_idx", "frame_index", "frame_number", "index"}
        for col in cols:
            if col.lower() in frame_name_candidates:
                frame_col = col
                break
        if frame_col is None and cols:
            first = cols[0]
            if first.lower().startswith("unnamed"):
                try:
                    ser = pd.to_numeric(df[first], errors="coerce")
                    if float(ser.notna().mean()) >= 0.95:
                        frame_col = first
                except Exception:
                    pass

        groups = {}
        order = []
        for col in cols:
            if col == frame_col:
                continue
            bodypart, coord = self._split_flat_coord_column(col)
            if coord is None:
                continue
            if bodypart not in groups:
                groups[bodypart] = {}
                order.append(bodypart)
            groups[bodypart][coord] = col

        if not groups:
            numeric_cols = []
            for col in cols:
                if col == frame_col:
                    continue
                try:
                    ser = pd.to_numeric(df[col], errors="coerce")
                except Exception:
                    continue
                if float(ser.notna().mean()) >= 0.95:
                    numeric_cols.append(col)
            if len(numeric_cols) >= 2:
                groups["centroid"] = {"x": numeric_cols[0], "y": numeric_cols[1]}
                order = ["centroid"]

        points = {}
        bodyparts = []
        for bp in order:
            item = groups.get(bp, {})
            if "x" not in item or "y" not in item:
                continue
            x = pd.to_numeric(df[item["x"]], errors="coerce").to_numpy(dtype=np.float32)
            y = pd.to_numeric(df[item["y"]], errors="coerce").to_numpy(dtype=np.float32)
            if "likelihood" in item:
                likelihood = pd.to_numeric(df[item["likelihood"]], errors="coerce").to_numpy(dtype=np.float32)
            else:
                likelihood = np.ones(len(df), dtype=np.float32)
            points[bp] = {"x": x, "y": y, "likelihood": likelihood}
            bodyparts.append(bp)

        if not points:
            raise ValueError("No usable coordinate columns were found. Expected frame/x/y or bodypart_x/bodypart_y columns.")

        if frame_col is not None:
            frame_numbers = (
                pd.to_numeric(df[frame_col], errors="coerce")
                .ffill()
                .bfill()
                .to_numpy(dtype=np.float64)
            )
            frame_numbers = np.round(frame_numbers).astype(np.int64)
            if len(frame_numbers) and frame_numbers[0] == 1 and np.array_equal(frame_numbers, np.arange(1, len(frame_numbers) + 1)):
                frame_numbers = frame_numbers - 1
        else:
            frame_numbers = np.arange(len(df), dtype=np.int64)

        return {
            "path": path,
            "format_name": "Coordinate table",
            "selected_individual": "",
            "bodyparts": bodyparts,
            "points": points,
            "n_frames": int(len(df)),
            "frame_numbers": frame_numbers,
            "frame_to_row": {int(v): int(i) for i, v in enumerate(frame_numbers)},
        }

    def _normalize_coord_name(self, value) -> str:
        s = str(value).strip().lower()
        if s in {"x", "xcoord", "x_coord"}:
            return "x"
        if s in {"y", "ycoord", "y_coord"}:
            return "y"
        if s in {"likelihood", "confidence", "conf", "p"}:
            return "likelihood"
        return s

    def _split_flat_coord_column(self, name: str):
        raw = str(name).strip()
        low = raw.lower()

        if low in {"x", "y", "likelihood", "confidence", "conf", "p"}:
            return "centroid", self._normalize_coord_name(low)

        m = re.match(r"^(.*?)[\s._-]+(x|y|likelihood|confidence|conf|p)$", low)
        if m:
            prefix = raw[: len(m.group(1))].strip(" ._-")
            return prefix or "centroid", self._normalize_coord_name(m.group(2))

        m = re.match(r"^(x|y|likelihood|confidence|conf|p)[\s._-]+(.*)$", low)
        if m:
            parts = re.split(r"[\s._-]+", raw, maxsplit=1)
            prefix = parts[1].strip() if len(parts) > 1 else "centroid"
            return prefix or "centroid", self._normalize_coord_name(m.group(1))

        return None, None

